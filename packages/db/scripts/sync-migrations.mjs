#!/usr/bin/env node
/**
 * Syncs drizzle-kit generated .sql files into src/migrations-generated.ts
 * so runtimes (web/worker/tests) apply migrations without filesystem
 * folder lookups — that trips webpack URL resolution and breaks
 * standalone builds. Run after `drizzle-kit generate`:
 *   pnpm --filter @pushpanel/db sync-migrations
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const migrationsDir = fileURLToPath(new URL("../src/migrations", import.meta.url));
const outFile = fileURLToPath(new URL("../src/migrations-generated.ts", import.meta.url));

const journal = JSON.parse(readFileSync(join(migrationsDir, "meta", "_journal.json"), "utf8"));
const entries = [];
for (const entry of journal.entries) {
  const sql = readFileSync(join(migrationsDir, `${entry.tag}.sql`), "utf8");
  entries.push({ tag: entry.tag, idx: entry.idx, sql });
}

const body = `// AUTO-GENERATED by scripts/sync-migrations.mjs — do not edit; re-run after
// \`drizzle-kit generate\`. Mirrors src/migrations (SQLite).

export interface MigrationEntry {
  idx: number;
  tag: string;
  sql: string;
}

export const migrations: MigrationEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(outFile, body);
console.log(`[sync-migrations] wrote ${outFile} (${entries.length} migrations)`);